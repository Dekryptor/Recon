using System.Text;

namespace Recon.Build;

/// <summary>
/// Renders the plan as a Ninja file (<c>build/build.ninja</c>). The file is an export, not a second
/// source of truth: every edge in it is the command <c>recon build</c> would run itself, with the
/// same flags, the same tools and the same depfiles.
/// </summary>
public static class NinjaWriter
{
    public static string Write(BuildPlan plan, BuildOptions options)
    {
        var text = new StringBuilder();
        text.Append("# Generated by recon ").Append(options.ToolVersion).Append(" - do not edit by hand.\n");
        text.Append("# `recon build` rewrites this file; run that instead of editing the build below.\n");
        text.Append("# Paths are relative to this file's directory.\n\n");
        text.Append("ninja_required_version = 1.5\n\n");

        var compiled = plan.Units.Where(u => !u.IsOriginal).ToList();
        bool withDepfile = compiled.Any(u => u.Profile?.Compile?.DepfileFlag.Length > 0);

        // One rule pair covers every toolchain: the differences live in the variables of each edge,
        // which is exactly where the profile data ends up.
        text.Append("rule cc\n");
        text.Append("  command = $cc $flags $in $out_flag");
        text.Append(withDepfile ? " $dep_flag\n" : "\n");
        text.Append("  description = CC $in\n");
        if (withDepfile)
        {
            text.Append("  deps = gcc\n");
            text.Append("  depfile = $dep_file\n");
        }

        text.Append("\nrule link\n");
        text.Append("  command = $link $flags $in $out_flag\n");
        text.Append("  description = LINK $out\n\n");

        foreach (var unit in compiled)
        {
            text.Append("build ").Append(Relative(plan, unit.ObjectPath)).Append(": cc ")
                .Append(Relative(plan, unit.SourcePath)).Append('\n');
            text.Append("  cc = ").Append(Tool(unit.Toolchain.Cc, unit.Toolchain.Wine)).Append('\n');
            text.Append("  flags = ").Append(EscapeAll(CompileFlagsRelative(plan, unit))).Append('\n');
            // The edge's own paths are relative to this file, so the flags that name them are too:
            // the file then keeps working even if the whole tree is moved.
            string outputFlag = BuildPlanner.Expand(
                unit.Profile?.Compile?.OutputFlag ?? string.Empty,
                ("obj", RelativeRaw(plan, unit.ObjectPath)));
            text.Append("  out_flag = ").Append(EscapeAll(BuildPlanner.SplitFlag(outputFlag))).Append('\n');
            if (unit.Profile?.Compile?.DepfileFlag.Length > 0)
            {
                string depFlag = BuildPlanner.Expand(
                    unit.Profile!.Compile.DepfileFlag,
                    ("dep", RelativeRaw(plan, unit.DepFilePath)));
                text.Append("  dep_flag = ").Append(EscapeAll(BuildPlanner.SplitFlag(depFlag))).Append('\n');
                text.Append("  dep_file = ").Append(Escape(RelativeRaw(plan, unit.DepFilePath))).Append('\n');
            }

            text.Append('\n');
        }

        if (plan.Links && compiled.Count > 0)
        {
            text.Append("build ").Append(Relative(plan, plan.OutputPath)).Append(": link");
            foreach (var unit in compiled)
            {
                text.Append(' ').Append(Relative(plan, unit.ObjectPath));
            }

            text.Append('\n');
            text.Append("  link = ").Append(Tool(plan.LinkExecutable, plan.LinkWine)).Append('\n');
            text.Append("  flags = ").Append(EscapeAll(plan.LinkFlags)).Append('\n');
            string linkOutput = BuildPlanner.Expand(plan.LinkOutputFlag, ("exe", RelativeRaw(plan, plan.OutputPath)));
            text.Append("  out_flag = ").Append(EscapeAll(BuildPlanner.SplitFlag(linkOutput))).Append('\n');
            text.Append("\ndefault ").Append(Relative(plan, plan.OutputPath)).Append('\n');
        }

        return text.ToString();
    }

    /// <summary>
    /// The unit's flags with its include directories made relative to this file: they are the only
    /// paths the flags carry, and an absolute one would break if the tree moved.
    /// </summary>
    private static List<string> CompileFlagsRelative(BuildPlan plan, PlannedUnit unit)
    {
        var flags = BuildPlanner.CompileFlags(unit);
        var includeFlag = unit.Profile?.Compile?.IncludeFlag ?? string.Empty;
        if (includeFlag.Length == 0)
        {
            return flags;
        }

        var result = new List<string>(flags.Count);
        foreach (string flag in flags)
        {
            string? replaced = null;
            foreach (string include in unit.Includes)
            {
                string rendered = BuildPlanner.Expand(includeFlag, ("path", include));
                if (string.Equals(flag, rendered, StringComparison.Ordinal))
                {
                    replaced = BuildPlanner.Expand(includeFlag, ("path", RelativeRaw(plan, include)));
                    break;
                }
            }

            result.Add(replaced ?? flag);
        }

        return result;
    }

    /// <summary>Ninja splits a command on whitespace and expands <c>$</c>, so both need escaping.</summary>
    private static string Escape(string text)
    {
        var builder = new StringBuilder(text.Length);
        foreach (char c in text)
        {
            switch (c)
            {
                case '$':
                    builder.Append("$$");
                    break;
                case ' ':
                    builder.Append("$ ");
                    break;
                case ':':
                    builder.Append("$:");
                    break;
                case '\n':
                case '\r':
                    builder.Append(' ');
                    break;
                default:
                    builder.Append(c);
                    break;
            }
        }

        return builder.ToString();
    }

    private static string EscapeAll(IEnumerable<string> words) => string.Join(' ', words.Select(Escape));

    /// <summary>A tool, with <c>wine</c> in front of it when the install says so.</summary>
    private static string Tool(string executable, bool wine)
        => wine ? "wine " + Escape(executable) : Escape(executable);

    /// <summary>A path relative to the Ninja file's directory, already escaped.</summary>
    private static string Relative(BuildPlan plan, string path) => Escape(RelativeRaw(plan, path));

    private static string RelativeRaw(BuildPlan plan, string path)
        => Path.GetRelativePath(plan.BuildDirectory, path).Replace(Path.DirectorySeparatorChar, '/');
}
